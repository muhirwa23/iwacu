//! Message types for actor communication

use crate::models::{ConstraintSatisfactionMatrix, ContextPayload, DiagnosticGraph};
use serde::{Deserialize, Serialize};

/// Messages sent between actors in the system
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum ActorMessage {
    /// From Orchestrator to Observe: request context for a task
    ObserveRequest { task: String },
    /// From Observe to Orchestrator: context payload ready
    ObserveResponse(ContextPayload),

    /// From Orchestrator to Plan: create a plan with context
    PlanRequest(ContextPayload),
    /// From Plan to Orchestrator: plan with constraints
    PlanResponse(PlanResult),

    /// From Orchestrator to Generate: generate code based on plan
    GenerateRequest(GenerateInput),
    /// From Generate to Orchestrator: generated diffs
    GenerateResponse(GenerateOutput),

    /// From Orchestrator to Apply: apply patches to worktree
    ApplyRequest(ApplyInput),
    /// From Apply to Orchestrator: application result
    ApplyResponse(ApplyResult),

    /// From Orchestrator to Test: run tests with mutation gate
    TestRequest(TestInput),
    /// From Test to Orchestrator: test results
    TestResponse(TestResult),

    /// From Orchestrator to Debug: debug compiler errors
    DebugRequest(DebugInput),
    /// From Debug to Orchestrator: fix proposal
    DebugResponse(DebugOutput),

    /// Internal: escalate to Plan node for non-local errors
    EscalateToPlan(EscalationPayload),
}

/// Result from the Plan actor
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PlanResult {
    /// High-level description of the plan
    pub description: String,
    /// Constraint satisfaction matrix
    pub constraints: ConstraintSatisfactionMatrix,
    /// Files to modify
    pub files_to_modify: Vec<String>,
    /// Whether user input is required
    pub requires_user_input: bool,
}

/// Input to the Generate actor
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GenerateInput {
    pub plan: PlanResult,
    pub context: ContextPayload,
}

/// Output from the Generate actor
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GenerateOutput {
    /// Diffs for each file (file_path -> diff)
    pub diffs: Vec<FileDiff>,
    /// Generated tests
    pub tests: Vec<TestSpec>,
}

/// A unified diff for a single file
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FileDiff {
    pub file_path: String,
    pub diff: String,
    pub new_content: Option<String>,
}

/// Test specification generated by LLM
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TestSpec {
    pub file_path: String,
    pub content: String,
    pub test_name: String,
}

/// Input to the Apply actor
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ApplyInput {
    /// Worktree ID to apply to
    pub worktree_id: String,
    /// Diffs to apply
    pub diffs: Vec<FileDiff>,
}

/// Result from applying patches
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ApplyResult {
    pub success: bool,
    pub worktree_id: String,
    pub applied_files: Vec<String>,
    pub error: Option<String>,
}

/// Input to the Test actor
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TestInput {
    pub worktree_id: String,
    pub test_specs: Vec<TestSpec>,
    /// Whether to run mutation testing
    pub run_mutation: bool,
}

/// Result from testing
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TestResult {
    pub passed: bool,
    pub compilation_failed: bool,
    pub diagnostic_graph: Option<DiagnosticGraph>,
    pub mutation_result: Option<MutationTestResult>,
    pub output: String,
}

/// Mutation testing result
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MutationTestResult {
    pub mutants_generated: usize,
    pub mutants_killed: usize,
    pub mutants_survived: usize,
    pub tests_valid: bool,
}

/// Input to the Debug actor
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DebugInput {
    pub diagnostic_graph: DiagnosticGraph,
    pub worktree_id: String,
    pub context: ContextPayload,
}

/// Output from the Debug actor
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DebugOutput {
    /// Proposed fixes
    pub fixes: Vec<FileDiff>,
    /// Whether to escalate to Plan
    pub escalate: bool,
    pub escalation_reason: Option<String>,
}

/// Payload for escalating to Plan node
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EscalationPayload {
    pub reason: String,
    pub context: ContextPayload,
    pub attempted_fixes: usize,
}
